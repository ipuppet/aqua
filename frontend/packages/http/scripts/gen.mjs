import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import openapiTS, { astToString } from "openapi-typescript"

const here = dirname(fileURLToPath(import.meta.url))
const openapiDir = resolve(here, "../../../../server/gen/openapi")
const outPath = resolve(here, "../src/gen/api.ts")

function listOpenApiFiles(dir) {
  const files = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) files.push(...listOpenApiFiles(path))
    else if (entry.name.endsWith(".openapi.json")) files.push(path)
  }
  return files.sort()
}

function mergeSpecs(specs) {
  const tags = new Map()
  const merged = {
    openapi: "3.1.0",
    info: { title: "aqua", version: "1.0.0" },
    paths: {},
    components: { schemas: {} },
    tags: []
  }

  for (const spec of specs) {
    for (const [path, item] of Object.entries(spec.paths ?? {})) {
      merged.paths[path] = { ...merged.paths[path], ...item }
    }
    Object.assign(merged.components.schemas, spec.components?.schemas ?? {})
    for (const tag of spec.tags ?? []) {
      tags.set(tag.name, tag)
    }
  }

  merged.tags = [...tags.values()]
  return merged
}

const files = listOpenApiFiles(openapiDir)
if (files.length === 0) {
  throw new Error(`no *.openapi.json files under ${openapiDir}; run buf generate first`)
}

const specs = files.map(file => JSON.parse(readFileSync(file, "utf8")))
const ast = await openapiTS(mergeSpecs(specs))
mkdirSync(dirname(outPath), { recursive: true })
writeFileSync(
  outPath,
  `/**
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */

${astToString(ast)}`
)
console.log(`merged ${files.length} specs -> ${outPath}`)
